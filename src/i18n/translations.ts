export const DICT: Record<Locale, TranslationDict> = { en, 'zh-CN': zhCN, 'zh-HK': zhHK }

// ============================================
// 工具函数
// ============================================
export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let text = DICT[locale]?.[key] || DICT['zh-CN']?.[key] || key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v))
    }
  }
  // 如果当前是 zh-HK 但没有翻译，用 zh-CN 并自动繁简转换（基础处理）
  return text
}

// 获取浏览器首选语言
export function getBrowserLocale(): Locale {
  if (typeof window === 'undefined') return 'zh-CN'
  const lang = navigator.language || 'zh-CN'
  if (lang.startsWith('zh-HK') || lang.startsWith('zh-TW')) return 'zh-HK'
  if (lang.startsWith('zh')) return 'zh-CN'
  if (lang.startsWith('en')) return 'en'
  return 'zh-CN'
}
