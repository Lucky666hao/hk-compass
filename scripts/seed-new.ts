async function main() {
  console.log('=== HK Compass — 第二批真实数据录入 ===')
  console.log(`共 ${NEW_COMPETITIONS.length} 条新数据\n`)

  // 先检查已有的标题，避免重复
  const { data: existing } = await supabase
    .from('competitions')
    .select('title')

  const existingTitles = new Set((existing || []).map((c: any) => c.title))

  const toInsert = NEW_COMPETITIONS.filter(c => {
    if (existingTitles.has(c.title)) {
      console.log(`⏭️  跳过重复: ${c.title}`)
      return false
    }
    return true
  })

  console.log(`\n新增: ${toInsert.length} 条 | 重複: ${NEW_COMPETITIONS.length - toInsert.length} 条\n`)

  if (toInsert.length === 0) {
    console.log('所有数据已存在，无需新增。')
    return
  }

  for (const comp of toInsert) {
    // 去掉 age_group 字段（数据库可能还没有这列）
    const { age_group, ...cleanComp } = comp as any
    const { error } = await supabase
      .from('competitions')
      .insert({
        ...cleanComp,
        view_count: 0,
      })

    if (error) {
      console.log(`❌ 失败: ${comp.title} — ${error.message}`)
    } else {
      console.log(`✅ 成功: ${comp.title} [${comp.type}]`)
    }
  }

  // 统计验证
  const { count } = await supabase
    .from('competitions')
    .select('*', { count: 'exact', head: true })

  console.log(`\n=== 数据库总数: ${count} ===`)
}

